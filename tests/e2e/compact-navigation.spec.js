test('More dialogs preserve drafts and restore focus to More', async ({ page, request }) => {
  await page.setViewportSize({ width: 633, height: 954 });
  await setup(page, request);
  await page.route('https://ko-fi.com/**', (route) => route.fulfill({ body: 'Support fixture' }));
  await page.getByRole('button', { name: 'New trade', exact: true }).click();
  const rationale = page.getByLabel('Entry rationale', { exact: true });
  await rationale.fill('Keep this unsaved idea');
  const route = page.url();
  const more = page.getByRole('button', { name: 'More', exact: true });
  await more.click();
  await page.getByRole('button', { name: 'About vxTradeJournal', exact: true }).click();
  const about = page.getByRole('dialog', { name: 'About vxTradeJournal' });
  await expect(about).toBeVisible();
  await expect(page.locator('.more-menu')).toBeHidden();
  await about.getByRole('button', { name: 'Support this project' }).click();
  await expect(page.getByRole('dialog')).toHaveCount(1);
  await page.getByRole('dialog', { name: 'Support vxTradeJournal' }).getByRole('button', { name: 'Close', exact: true }).click();
  await expect(more).toBeFocused();
  await more.click();
  await page.locator('.more-menu').getByRole('button', { name: 'Support this project' }).click();
  await page.keyboard.press('Escape');
  await expect(more).toBeFocused();
  await expect(rationale).toHaveValue('Keep this unsaved idea');
  expect(page.url()).toBe(route);
  page.once('dialog', (dialog) => dialog.dismiss());
  await more.click();
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  await expect(rationale).toHaveValue('Keep this unsaved idea');
  expect(page.url()).toBe(route);
});

test('responsive navigation retains desktop actions and closes More on resize', async ({ page, request }) => {
  await setup(page, request);
  const sidebar = page.locator('.sidebar');
  const more = sidebar.getByRole('button', { name: 'More', exact: true });
  const settings = sidebar.getByRole('button', { name: 'Settings', exact: true });
  for (const width of [701, 768, 1440]) {
    await page.setViewportSize({ width, height: 954 });
    await expect(more).toBeHidden();
    await expect(settings).toBeVisible();
    await expect(sidebar.getByRole('button', { name: 'About vxTradeJournal', exact: true })).toBeVisible();
    await expect(sidebar.getByRole('button', { name: 'Support this project', exact: true })).toBeVisible();
    await page.screenshot({ path: test.info().outputPath(`test-results/compact-navigation-${width}-desktop.png`.split("/").pop()), fullPage: true });
  }
  await page.setViewportSize({ width: 633, height: 954 });
  await more.click();
  await settings.focus();
  await page.setViewportSize({ width: 768, height: 954 });
  await expect(page.locator('.more-menu')).toBeHidden();
  await expect(settings).toBeVisible();
  await expect(settings).toBeFocused();
  await page.setViewportSize({ width: 633, height: 954 });
  await expect(more).toBeFocused();
  await expect(settings).toBeHidden();
  await expect(sidebar.locator('[data-route="settings"]')).toHaveCount(1);
  await expect(sidebar.locator('.support-trigger')).toHaveCount(1);
  await more.click();
  const reload = sidebar.getByRole('button', { name: 'Reload records', exact: true });
  await reload.focus();
  await page.setViewportSize({ width: 768, height: 954 });
  await expect(reload).toBeFocused();
  await expect(sidebar.locator('.session-slot .session-details')).toBeVisible();
  await expect(sidebar.locator('.session-slot').getByRole('button', { name: 'Reload records', exact: true })).toBeVisible();
  await page.setViewportSize({ width: 633, height: 954 });
  await expect(more).toBeFocused();
  await expect(reload).toBeHidden();
});

test('compact More includes Session controls and preserves their draft guards', async ({ page, request }) => {
  await page.setViewportSize({ width: 633, height: 954 });
  await setup(page, request);
  const more = page.getByRole('button', { name: 'More', exact: true });
  const menu = page.locator('.more-menu');
  await more.click();
  await expect(menu.getByRole('button', { name: 'Reload records', exact: true })).toBeVisible();
  await expect(menu.locator('.session-profile p')).toHaveText(/@example\.test$/);
  await menu.getByRole('button', { name: 'Reload records', exact: true }).click();
  await expect(menu).toBeHidden();
  await expect(page.getByRole('heading', { name: 'Journal', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'New trade', exact: true }).click();
  const rationale = page.getByLabel('Entry rationale', { exact: true });
  await rationale.fill('Preserve this draft when Session actions are rejected');
  const route = page.url();
  for (const name of ['Reload records', 'Sign out']) {
    await more.click();
    page.once('dialog', (dialog) => dialog.dismiss());
    await menu.getByRole('button', { name, exact: true }).click();
    await expect(menu).toBeHidden();
    await expect(more).toBeFocused();
    await expect(rationale).toHaveValue('Preserve this draft when Session actions are rejected');
    expect(page.url()).toBe(route);
  }
  await more.click();
  page.once('dialog', (dialog) => dialog.accept());
  await menu.getByRole('button', { name: 'Reload records', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'New trade', exact: true })).toBeVisible();
  await expect(rationale).toHaveValue('');
  await more.click();
  await menu.getByRole('button', { name: 'Sign out', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Sign in', exact: true })).toBeVisible();
});

test('merged More remains scrollable on a short compact viewport', async ({ page, request }) => {
  await page.setViewportSize({ width: 320, height: 360 });
  await setup(page, request);
  const more = page.getByRole('button', { name: 'More', exact: true });
  await more.click();
  const menu = page.locator('.more-menu');
  // Native popover toggle events are queued after the activating click.
  await expect.poll(async () => {
    const bounds = await menu.boundingBox();
    return bounds ? bounds.y + bounds.height : Infinity;
  }).toBeLessThanOrEqual(360);
  const bounds = await menu.boundingBox();
  expect(bounds.y).toBeGreaterThanOrEqual(0);
  expect(bounds.y + bounds.height).toBeLessThanOrEqual(360);
  const download = menu.getByRole('link', { name: 'Download agent skill (ZIP)', exact: true });
  await download.focus();
  const linkBounds = await download.boundingBox();
  expect(linkBounds.y).toBeGreaterThanOrEqual(bounds.y);
  expect(linkBounds.y + linkBounds.height).toBeLessThanOrEqual(bounds.y + bounds.height);
  await page.screenshot({ path: test.info().outputPath('test-results/compact-navigation-320-short.png'.split("/").pop()), fullPage: true });
  await page.keyboard.press('Escape');
  await expect(more).toBeFocused();
});

