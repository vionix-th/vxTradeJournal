import { test, expect, setup } from "./fixtures.js";
import { openTradeDraft } from "./audit-editor-fixtures.js";

for (const width of [800]) test(`invalid foreign result rate stays reachable on Entry at ${width}px`, async ({ page, request }) => {
  await page.setViewportSize({ width, height: 900 });
  await setup(page, request);
  await openTradeDraft(page);
  await page.getByRole("button", { name: "Cancel", exact: true }).click();
  await page.getByRole("button", { name: "Instruments", exact: true }).click();
  await page.getByRole("button", { name: "Edit instrument", exact: true }).click();
  await page.getByLabel("P&L currency", { exact: true }).fill("EUR");
  await page.getByRole("button", { name: "Save instrument", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Instruments", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Journal", exact: true }).click();
  await page.getByRole("button", { name: "New trade", exact: true }).click();
  await page.getByRole("button", { name: "Save trade", exact: true }).click();
  await page.getByRole("button", { name: "Add execution", exact: true }).click();
  await page.getByLabel("Record type", { exact: true }).selectOption("exit");
  const rate = page.getByLabel("Result conversion rate", { exact: true });
  await rate.fill("-1");
  await page.getByLabel("Record type", { exact: true }).selectOption("entry");
  await expect(rate).toBeVisible();
  await expect(rate).toHaveAttribute("aria-invalid", "true");
  await expect(rate).toHaveAccessibleDescription(/must be positive/);
  await page.getByLabel("Quantity", { exact: true }).fill("1");
  await page.getByLabel("Price", { exact: true }).fill("10");
  await page.getByLabel("Fee currency", { exact: true }).fill("USD");
  await page.getByRole("button", { name: "Save execution", exact: true }).click();
  await expect(page.getByRole("alert")).toContainText("Result conversion rate must be positive");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true);
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: test.info().outputPath(`test-results/final-validation-${width}.png`.split("/").pop()), fullPage: true });
  await rate.focus();
  await page.keyboard.press("ControlOrMeta+A");
  await page.keyboard.type("0.8");
  await expect(rate).toBeHidden();
  await page.getByRole("button", { name: "Save execution", exact: true }).click();
  await expect(page.getByRole("button", { name: "Edit execution 1", exact: true })).toBeVisible();
});
