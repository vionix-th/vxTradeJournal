import { test, expect } from "@playwright/test";
import { setup } from "./fixtures.js";
async function instrument(page, name, unit, currency = "USD", preset = "equity") {
  await page.getByRole("button", { name: "Instruments", exact: true }).click();
  await page.getByRole("button", { name: "New instrument", exact: true }).click();
  await page.getByLabel("Instrument name", { exact: true }).fill(name);
  await page.getByLabel("Symbol", { exact: true }).fill(name.toUpperCase());
  await page.getByLabel("Preset", { exact: true }).selectOption(preset);
  await page.getByLabel("Price unit", { exact: true }).fill(unit);
  await page.getByLabel("P&L currency", { exact: true }).fill(currency);
  await page.getByRole("button", { name: "Save instrument", exact: true }).click();
  await expect(page.getByRole("heading", { name, exact: true })).toBeVisible();
}
const leg = (page, index = 1) => page.getByRole("group", { name: `Leg ${index}`, exact: true });
async function openPlan(group) { await group.locator("summary").filter({ hasText: /^Trade plan$/ }).click(); }
async function openSizing(group) { await group.locator("summary").filter({ hasText: /^Position sizing$/ }).click(); }

for (const width of [1280, 996, 375]) {
  test(`optional trade plan and clear units at ${width}px`, async ({ page, request }) => {
    await page.setViewportSize({ width, height: 900 });
    await setup(page, request);
    await instrument(page, "Acme", "USD/share");
    await page.getByRole("button", { name: "Journal", exact: true }).click();
    await page.getByRole("button", { name: "New trade", exact: true }).click();
    const first = leg(page);
    await expect(first.getByLabel("Instrument", { exact: true })).toBeVisible();
    await expect(first.getByLabel("Entry price", { exact: true })).not.toBeVisible();
    await openPlan(first);
    await expect(first.getByLabel("Entry price", { exact: true })).toHaveAccessibleDescription("USD/share");
    await expect(first.getByLabel("Quantity", { exact: true })).toHaveAccessibleDescription("shares");
    await openSizing(first);
    await expect(first.getByLabel("Risk budget", { exact: true })).toHaveAccessibleDescription("USD");
    await expect(first.getByRole("status")).toContainText("Enter entry price, stop price and risk budget");
    await first.getByLabel("Risk budget", { exact: true }).fill("-1");
    await expect(first.getByRole("status")).toContainText("positive");
    await first.getByLabel("Risk budget", { exact: true }).fill("500");
    await first.getByLabel("Entry price", { exact: true }).fill("10");
    await first.getByLabel("Stop price", { exact: true }).fill("8");
    await expect(first.getByRole("status")).toContainText("250 shares");
    await expect(first.getByRole("status")).toContainText("500.00 USD");
    await page.getByRole("button", { name: "Add leg", exact: true }).click();
    await expect(first.getByLabel("Entry price", { exact: true })).toBeVisible();
    await expect(first.getByLabel("Risk budget", { exact: true })).not.toBeVisible();
    await expect(page.getByLabel("Combined risk budget", { exact: true })).toHaveAccessibleDescription(/USD/);
    await openPlan(leg(page, 2));
    await expect(leg(page, 2).getByRole("status")).toContainText("combined risk manually");
    await expect(page.getByText("Intended prices and size. Record actual fills separately.", { exact: true }).filter({ visible: true })).toHaveCount(1);
    await openPlan(first);
    await expect(leg(page, 2).getByText("Intended prices and size. Record actual fills separately.", { exact: true })).toBeVisible();
    await openPlan(first);
    await expect(page.getByText("Intended prices and size. Record actual fills separately.", { exact: true }).filter({ visible: true })).toHaveCount(1);
    await leg(page, 2).getByRole("button", { name: "Remove leg", exact: true }).click();
    await expect(first.getByLabel("Risk budget", { exact: true })).toBeVisible();
    await page.getByRole("button", { name: "Create instrument", exact: true }).click();
    await page.getByLabel("Instrument name", { exact: true }).fill("Inline");
    await page.getByLabel("Symbol", { exact: true }).fill("INL");
    await page.getByLabel("Price unit", { exact: true }).fill("points");
    await page.getByRole("button", { name: "Save instrument", exact: true }).click();
    await expect(leg(page).getByLabel("Entry price", { exact: true })).toHaveValue("10");
    await expect(leg(page).getByLabel("Risk budget", { exact: true })).toBeVisible();
    await page.screenshot({ path: `test-results/trade-plan-${width}.png`, fullPage: true });
    await page.getByRole("button", { name: "Save trade", exact: true }).click();
    await page.getByRole("button", { name: "Edit trade", exact: true }).click();
    await expect(leg(page).getByLabel("Entry price", { exact: true })).toBeVisible();
    await expect(leg(page).getByLabel("Risk budget", { exact: true })).toBeVisible();
    expect((await page.locator("label").allTextContents()).some((text) => text.includes("(leg"))).toBe(false);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true);
  });
}

test("units follow currency pairs, manual models and historical snapshots", async ({ page, request }) => {
  await setup(page, request);
  await instrument(page, "Euro", "EUR/share", "EUR");
  await instrument(page, "Dollar", "USD/share");
  await instrument(page, "Option", "", "USD", "options");
  await page.getByRole("button", { name: "Accounts", exact: true }).click();
  await page.getByRole("button", { name: "New account", exact: true }).click();
  await page.getByLabel("Account name", { exact: true }).fill("Euro account");
  await page.getByLabel("Reporting currency", { exact: true }).fill("EUR");
  await page.getByRole("button", { name: "Save account", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Accounts", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Journal", exact: true }).click();
  await page.getByRole("button", { name: "New trade", exact: true }).click();
  const first = leg(page);
  await page.getByLabel("Account", { exact: true }).selectOption({ label: "Main" });
  await first.getByLabel("Instrument", { exact: true }).selectOption({ label: "Euro" });
  await openPlan(first); await openSizing(first);
  await expect(first.getByLabel("Conversion rate", { exact: true })).toHaveAccessibleDescription("1 EUR = rate USD");
  await first.getByLabel("Conversion rate", { exact: true }).fill("0.8");
  await page.getByLabel("Account", { exact: true }).selectOption({ label: "Euro account" });
  await expect(first.getByLabel("Conversion rate", { exact: true })).toHaveValue("1");
  await expect(first.getByLabel("Conversion rate", { exact: true })).not.toBeVisible();
  await page.getByLabel("Account", { exact: true }).selectOption({ label: "Main" });
  await expect(first.getByLabel("Conversion rate", { exact: true })).toHaveValue("");
  await first.getByLabel("Conversion rate", { exact: true }).fill("0.8");
  await first.getByLabel("Instrument", { exact: true }).selectOption({ label: "Dollar" });
  await first.getByLabel("Instrument", { exact: true }).selectOption({ label: "Euro" });
  await expect(first.getByLabel("Conversion rate", { exact: true })).toHaveValue("");
  await first.getByLabel("Instrument", { exact: true }).selectOption({ label: "Option" });
  await expect(first.getByLabel("Entry price", { exact: true })).toHaveAccessibleDescription("Quote unit not configured.");
  await expect(first.locator("summary").filter({ hasText: /^Position sizing$/ })).not.toBeVisible();
  await first.getByLabel("Instrument", { exact: true }).selectOption({ label: "Euro" });
  await first.getByLabel("Quantity", { exact: true }).fill("2");
  await page.getByRole("button", { name: "Save trade", exact: true }).click();
  await expect(page.getByRole("button", { name: "Edit trade", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Instruments", exact: true }).click();
  const card = page.locator("section").filter({ has: page.getByRole("heading", { name: "Euro", exact: true }) });
  await card.getByRole("button", { name: "Edit instrument", exact: true }).click();
  await page.getByLabel("Price unit", { exact: true }).fill("Changed quotation unit");
  await page.getByRole("button", { name: "Save instrument", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Instruments", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Journal", exact: true }).click();
  await page.getByRole("button", { name: "Open trade", exact: true }).first().click();
  await page.getByRole("button", { name: "Edit trade", exact: true }).click();
  await expect(leg(page).getByLabel("Entry price", { exact: true })).toHaveAccessibleDescription("EUR/share");
  await page.getByRole("button", { name: "Cancel", exact: true }).click();
  await page.getByRole("button", { name: "Settings", exact: true }).click();
  await page.getByLabel("Theme", { exact: true }).selectOption("dark");
  await page.getByRole("button", { name: "Save settings", exact: true }).click();
  await expect(page.locator("html")).toHaveAttribute("data-theme", "dark");
  await expect(page.getByRole("button", { name: "Save settings", exact: true })).toBeEnabled();
  await page.getByRole("button", { name: "Journal", exact: true }).click();
  await page.getByRole("button", { name: "Open trade", exact: true }).first().click();
  await page.getByRole("button", { name: "Edit trade", exact: true }).click();
  await openSizing(leg(page));
  await expect(leg(page).getByLabel("Conversion rate", { exact: true })).toHaveAccessibleDescription("1 EUR = rate USD");
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: "test-results/trade-plan-dark.png", fullPage: true });
});
